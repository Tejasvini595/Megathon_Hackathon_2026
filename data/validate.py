"""Plausibility, consistency, leakage and privacy checks on data/out.

    uv run python validate.py   -> prints a report and writes out/validation_report.md + .json
"""
import json

import numpy as np
import pandas as pd

from gen.constants import sap_to_band
from gen.paths import HIDDEN, OUT, RAW

R = {}
lines = ["# Validation report", "", "Generated by `validate.py`. Benchmarks are cited in sources.md.", ""]
fails = []


def check(name, ok, detail):
    R[name] = {"pass": bool(ok), "detail": detail}
    lines.append(f"- **{'PASS' if ok else 'FAIL'}** {name}: {detail}")
    if not ok:
        fails.append(name)


p = pd.read_parquet(OUT / "properties.parquet")
eu = pd.read_parquet(OUT / "energy_usage.parquet")
sp = pd.read_parquet(OUT / "splits.parquet")
lp = pd.read_parquet(OUT / "labels_package.parquet")
lv = pd.read_parquet(OUT / "labels_value.parquet")
sh = pd.read_parquet(OUT / "sales_history.parquet")
comp = pd.read_parquet(HIDDEN / "true_annual_components.parquet")
faults = pd.read_parquet(HIDDEN / "fault_log.parquet")

# ---------------------------------------------------------------- 1 consistency
lines += ["", "## 1. Consistency", ""]
bad = (p["sap_score"].map(sap_to_band) != p["energy_rating"]).sum()
check("rating band matches SAP score", bad == 0, f"{bad} mismatches in {len(p):,} homes")
check("one row per property", p["property_id"].is_unique, f"{len(p):,} unique property_id")
months = eu.groupby("property_id").size()
check("24 monthly rows per home", (months == 24).all(), f"rows per home min {months.min()}, max {months.max()}")

# ---------------------------------------------------------------- 2 missing data
lines += ["", "## 2. Missing data is NaN, never zero", ""]
gas_users = set(comp.loc[comp["gas_kwh"] > 0, "property_id"])
eg = eu[eu["property_id"].isin(gas_users)]
zeros = (eg["gas_kwh"] == 0).sum()
check("gas users have no zero months", zeros == 0, f"{zeros} zero gas readings among gas users; missing = NaN ({eg['gas_kwh'].isna().mean():.1%} of their months)")
obs = eu.groupby("property_id")["electricity_kwh"].apply(lambda s: s.notna().sum())
winter = eu[eu["month"].str[5:].isin(["12", "01", "02"])].groupby("property_id")["electricity_kwh"].apply(lambda s: s.notna().sum())
unavail = ((obs < 6) | (winter.reindex(obs.index).fillna(0) == 0)).sum()
check("homes below the annualisation threshold exist (test cases)", unavail > 0,
      f"{unavail:,} homes have <6 months or no winter month -> consumption 'unavailable'")
lines.append(f"- Fault log: {faults['fault'].value_counts().to_dict()}")

# ---------------------------------------------------------------- 3 energy plausibility
lines += ["", "## 3. Energy plausibility (true annual values before faults)", ""]
m = p.merge(comp.drop(columns=["heating_fuel", "hot_water_fuel"]), on="property_id")
g = m[(m["fuel_scope"] == "gas_elec") & (m["gas_kwh"] > 0)]
gm = g["gas_kwh"].median()
check("median gas within 15% of NEED 2026 (10,000 kWh, 2024)", abs(gm / 10000 - 1) < 0.15, f"simulated median {gm:,.0f} kWh (IQR {g['gas_kwh'].quantile(.25):,.0f}-{g['gas_kwh'].quantile(.75):,.0f})")
em = m.loc[m["heating"] == "gas_boiler", "grid_import_kwh"].median()
check("median electricity of gas-heated homes within 20% of NEED (2,500 kWh, all homes)", abs(em / 2500 - 1) < 0.20, f"simulated median {em:,.0f} kWh")
houses = g[g["property_type"].isin(["House", "Bungalow"])]
ipm = (houses["gas_kwh"] / houses["floor_area"]).median()
check("house gas intensity near NEED (~105 kWh/m2 for 51-150 m2 houses)", 80 < ipm < 140, f"simulated median {ipm:.0f} kWh/m2 (NEED floor areas are HMRC/VOA-based, EPC areas run smaller)")
bm = g.groupby("energy_rating")["gas_kwh"].median().round(-1).to_dict()
lines.append(f"- Median gas by EPC band: {bm}")
lines.append(f"- Median gas by property type: {g.groupby('property_type')['gas_kwh'].median().round(-1).to_dict()}")
lines.append(f"- Median grid electricity by heating: {m.groupby('heating')['grid_import_kwh'].median().round(-1).to_dict()}")
ge = m[m["fuel_scope"] == "gas_elec"]
r_sim = np.corrcoef(ge["sap_score"], (ge["gas_kwh"] + ge["grid_import_kwh"]) / ge["floor_area"])[0, 1]
r_epc = np.corrcoef(ge["sap_score"], ge["epc_primary_kwh_m2"])[0, 1]
check("metered intensity is not a copy of the rating", abs(r_sim) < abs(r_epc) - 0.15,
      f"corr(SAP, simulated kWh/m2) = {r_sim:.2f} vs corr(SAP, EPC modelled kWh/m2) = {r_epc:.2f}")

# real DESNZ postcode medians vs simulated postcode medians
for fuel, f, col in [("gas", "Postcode_level_gas_2024.csv", "gas_kwh"), ("electricity", "Postcode_level_all_meters_electricity_2024.csv", "elec_demand_kwh")]:
    dz = pd.read_csv(RAW / f"desnz/{f}")
    dz["Postcode"] = dz["Postcode"].str.upper().str.strip()
    real = dz.set_index("Postcode")["Median_cons_kwh"]
    sub = m[m[col] > 0].groupby("postcode")[col].agg(["median", "size"])
    sub = sub[sub["size"] >= 3].join(real.rename("real"), how="inner")
    rho = sub[["median", "real"]].corr(method="spearman").iloc[0, 1]
    check(f"simulated vs real DESNZ postcode median {fuel} correlate", rho > 0.3,
          f"Spearman {rho:.2f} over {len(sub):,} postcodes with >=3 homes (partial pooling, exponent 0.5)")

# ---------------------------------------------------------------- 4 value
lines += ["", "## 4. Property value", ""]
hpi = pd.read_csv(RAW / "landregistry/UK-HPI-full-file-2026-07.csv")
hpi["month"] = pd.to_datetime(hpi["Date"], dayfirst=True).dt.to_period("M").astype(str)
hv = hpi[hpi["month"] == "2026-07"].set_index("RegionName")["AveragePrice"]
la = p.groupby("local_authority")["current_value_estimate"].median()
rows = []
for k, v in la.items():
    ref = hv.get({"Bristol, City of": "City of Bristol"}.get(k, k))
    rows.append(f"{k}: ours {v:,.0f} vs HPI average {ref:,.0f}")
lines.append("- Median current value vs UK HPI average price (Jul 2026), by council: " + "; ".join(rows))
lines.append(f"- Value source: {p['value_source'].value_counts().to_dict()}")
check("current value kept separate from sale prices", "price" not in p.columns and "current_value_estimate" in p.columns,
      "properties.current_value_estimate (valuation 2026-07) vs sales_history.price (historical)")
log = json.loads((OUT / "build_log.json").read_text())
vm = log["value_model"]
check("value model beats outcode GBP/m2 baseline", vm["median_ape_lightgbm"] < vm["median_ape_baseline_outcode_gbp_per_m2"],
      f"median APE {vm['median_ape_lightgbm']:.3f} vs baseline {vm['median_ape_baseline_outcode_gbp_per_m2']:.3f} (GroupKFold by postcode)")
rp = log["rating_premium"]
check("rating premium estimated from real sales", rp["n_sales"] > 1000,
      f"{rp['coef_log_price_per_10_sap']:.3f} log-price per 10 SAP points, 95% CI {rp['ci95']}, n={rp['n_sales']:,} (associational)")

# ---------------------------------------------------------------- 5 labels
lines += ["", "## 5. Labels", ""]
ip = lp["improvement_potential_pct"]
check("improvement potential unavailable only with a reason", (lp.loc[ip.isna(), "improvement_potential_unavailable_reason"] != "").all(),
      f"{ip.isna().sum():,} unavailable, all with a reason")
rho = lp[["improvement_potential_pct_no_heat_pump", "epc_potential_improvement_pct"]].corr(method="spearman").iloc[0, 1]
lines.append(f"- Spearman(simulated improvement potential without heat pump, EPC potential improvement) = {rho:.2f}")
lines.append(f"- Improvement potential median: with heat pump {ip.median():.1f}%, without {lp['improvement_potential_pct_no_heat_pump'].median():.1f}%")
lines.append(f"- Value uplift mid (median over homes with an EPC improvement): {lv.loc[lv['sap_after'] > lv['sap_before'], 'uplift_pct_mid'].median():.2f}%")

# P10001-style test homes (brief example)
q = p[(p["energy_rating"] == "E") & (p["glazing"] == "single") & (p["heating"] == "gas_boiler") & (p["solar_kwp_est"].fillna(0) == 0)
      & (p["wall_insulation"] == "none")]
check("brief's P10001 profile is represented", len(q) > 0, f"{len(q)} homes rated E with single glazing, uninsulated walls, gas boiler, no PV")

# ---------------------------------------------------------------- 6 leakage & privacy
lines += ["", "## 6. Leakage and privacy", ""]
spp = sp.groupby("postcode_group")["split"].nunique()
check("no postcode spans two splits", (spp <= 1).all(), f"{(spp > 1).sum()} postcodes in >1 split; split sizes {sp['split'].value_counts().to_dict()}")
lv_ = sp.merge(p[["property_id", "local_authority"]])
check("Liverpool only in geo_test", (lv_.loc[lv_["local_authority"] == "Liverpool", "split"] == "geo_test").all(), "unseen-city test set")
banned = {"uprn", "address1", "address2", "address3", "address"}
leaked = {f.name: sorted(banned & set(pd.read_parquet(f).columns)) for f in OUT.glob("*.parquet")}
leaked = {k: v for k, v in leaked.items() if v}
check("no UPRN or street address in shipped files", not leaked, f"offending files: {leaked}" if leaked else "none (UPRN/address only in hidden/crosswalk)")
check("simulated energy rows tagged", (eu["source"] == "simulated").all(), "energy_usage.source == 'simulated'")

lines += ["", f"**{len(R) - len(fails)}/{len(R)} checks passed.**" + (f" Failed: {fails}" if fails else "")]
(OUT / "validation_report.md").write_text("\n".join(lines) + "\n")
(OUT / "validation_report.json").write_text(json.dumps(R, indent=2))
print("\n".join(lines))
